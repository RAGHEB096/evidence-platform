import { ArrowLeftIcon, FileTextIcon, ImageIcon } from 'lucide-react'
import { Link, useParams } from 'react-router'
import { PageHeader } from '@/components/PageHeader'
import { EmptyState } from '@/components/states/EmptyState'
import { ErrorState } from '@/components/states/ErrorState'
import { LoadingState } from '@/components/states/LoadingState'
import { StatusBadge } from '@/components/StatusBadge'
import { Button } from '@/components/ui/button'
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui/table'
import { EXPORT_STATUSES } from '@/domain/status'
import { useSignedUrls } from '@/features/evidence/api'
import { useExportDetail } from '@/features/reports/api'
import { DownloadReportButton } from '@/features/reports/DownloadReportButton'
import { useUserDirectory } from '@/features/users/api'
import { toUserMessage } from '@/lib/errors'
import { formatBytes, formatDateTime } from '@/lib/format'

/** One export's record: who generated it and when, its file, and the evidence it contained. */
export function ExportDetailPage() {
  const { exportId = '' } = useParams()
  const detail = useExportDetail(exportId)
  const directory = useUserDirectory()
  const evidencePaths = (detail.data?.items ?? []).flatMap((item) => (item.evidence ? [item.evidence.storage_path] : []))
  const urls = useSignedUrls(evidencePaths)

  if (detail.isPending) return <LoadingState label="Loading report…" />
  if (detail.isError) return <ErrorState message={toUserMessage(detail.error)} onRetry={() => void detail.refetch()} />
  const row = detail.data.export
  if (!row) {
    return (
      <EmptyState
        icon={FileTextIcon}
        title="Report not available"
        description="This report does not exist, or it belongs to a protocol you are not assigned to."
        action={
          <Button asChild variant="outline">
            <Link to="/documents">Back to Generated Documents</Link>
          </Button>
        }
      />
    )
  }

  const name = (id: string | null) => (id ? (directory.data?.get(id)?.display_name ?? 'Unknown user') : '—')

  return (
    <>
      <Button asChild variant="ghost" size="sm" className="-ml-2 w-fit">
        <Link to="/documents">
          <ArrowLeftIcon aria-hidden="true" />
          Generated Documents
        </Link>
      </Button>
      <PageHeader
        title={row.name}
        description={
          <span className="flex flex-wrap items-center gap-2">
            <span className="font-mono">{row.protocol?.reference}</span>
            <span>{row.protocol?.name}</span>
            <StatusBadge status={EXPORT_STATUSES[row.status]} />
          </span>
        }
        actions={
          row.status === 'generated' ? (
            <DownloadReportButton row={row} size="default" />
          ) : (
            <Button asChild>
              <Link to={`/protocols/${row.protocol_id}/report`}>Open in report builder</Link>
            </Button>
          )
        }
      />

      <dl className="grid max-w-2xl gap-x-6 gap-y-1 text-sm sm:grid-cols-[max-content_1fr]">
        <dt className="text-muted-foreground">Generated</dt>
        <dd>{formatDateTime(row.generated_at)}</dd>
        <dt className="text-muted-foreground">Generated by</dt>
        <dd>{name(row.generated_by)}</dd>
        <dt className="text-muted-foreground">Contents</dt>
        <dd>
          {row.chapter_count ?? '—'} chapters · {row.test_run_count ?? '—'} test runs · {row.step_count ?? '—'} steps · {row.image_count ?? '—'} images
        </dd>
        <dt className="text-muted-foreground">Steps without evidence</dt>
        <dd>{row.include_steps_without_evidence ? 'Included' : 'Left out'}</dd>
        <dt className="text-muted-foreground">Saved file</dt>
        <dd>{row.storage_path ? `${formatBytes(row.file_size_bytes ?? 0)}` : 'Not saved (downloaded only)'}</dd>
        <dt className="text-muted-foreground">File SHA-256</dt>
        <dd className="font-mono text-xs break-all">{row.sha256 ?? '—'}</dd>
      </dl>

      <section aria-labelledby="contained-evidence" className="space-y-2">
        <h2 id="contained-evidence" className="font-semibold">
          Evidence selected ({detail.data.items.length})
        </h2>
        <div className="rounded-lg border">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead className="w-24">Image</TableHead>
                <TableHead>File</TableHead>
                <TableHead>Caption in report</TableHead>
                <TableHead>SHA-256</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {detail.data.items.map((item) => {
                const evidence = item.evidence
                const url = evidence ? urls.data?.get(evidence.storage_path) : undefined
                return (
                  <TableRow key={item.id}>
                    <TableCell>
                      <div className="flex h-12 w-16 items-center justify-center overflow-hidden rounded bg-muted">
                        {url ? <img src={url} alt="" loading="lazy" className="size-full object-contain" /> : <ImageIcon aria-hidden="true" className="size-4 text-muted-foreground" />}
                      </div>
                    </TableCell>
                    <TableCell>
                      {evidence ? evidence.original_filename : 'Evidence no longer available'}
                      {evidence?.deleted_at ? <span className="ml-2 text-xs text-muted-foreground">(archived since)</span> : null}
                    </TableCell>
                    <TableCell>{item.caption_override ?? evidence?.caption ?? '—'}</TableCell>
                    <TableCell className="font-mono text-xs">{evidence ? `${evidence.sha256.slice(0, 16)}…` : '—'}</TableCell>
                  </TableRow>
                )
              })}
            </TableBody>
          </Table>
        </div>
      </section>
    </>
  )
}
