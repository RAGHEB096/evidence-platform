import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { PROFILE_COLUMNS, type Profile } from '@/auth/profile'
import type { ProtocolRole } from '@/domain/roles'
import { invokeFunction } from '@/lib/functions'
import { getSupabase } from '@/lib/supabase'

export interface AdminUserRow extends Profile {
  created_at: string
}

export interface AccessRow {
  id: string
  role: ProtocolRole
  granted_at: string
  protocol: { id: string; name: string; reference: string; deleted_at: string | null } | null
}

export const userKeys = {
  all: ['admin', 'users'] as const,
  access: (userId: string) => ['admin', 'users', userId, 'access'] as const,
  directory: ['user-directory'] as const,
}

/** Administrators see every profile through RLS; nobody else gets more than their own row. */
export function useAdminUsers() {
  return useQuery({
    queryKey: userKeys.all,
    queryFn: async () => {
      const { data, error } = await getSupabase()
        .from('user_profiles')
        .select(`${PROFILE_COLUMNS}, created_at`)
        .order('username')
      if (error) throw error
      return data as AdminUserRow[]
    },
  })
}

export function useUserAccess(userId: string) {
  return useQuery({
    queryKey: userKeys.access(userId),
    queryFn: async () => {
      const { data, error } = await getSupabase()
        .from('protocol_access')
        .select('id, role, granted_at, protocol:protocols(id, name, reference, deleted_at)')
        .eq('user_id', userId)
        .order('granted_at')
      if (error) throw error
      return data as unknown as AccessRow[]
    },
  })
}

export interface DirectoryEntry {
  id: string
  username: string
  display_name: string
  is_active: boolean
}

/** Names for display (uploader, generated by, audit actor). */
export function useUserDirectory() {
  return useQuery({
    queryKey: userKeys.directory,
    queryFn: async () => {
      const { data, error } = await getSupabase().rpc('user_directory')
      if (error) throw error
      return new Map((data as DirectoryEntry[]).map((entry) => [entry.id, entry]))
    },
    staleTime: 5 * 60_000,
  })
}

export type AdminUsersRequest =
  | { action: 'create'; username: string; displayName: string; password: string; isAdmin: boolean; canCreateProtocols: boolean }
  | { action: 'reset_password'; userId: string; password: string }
  | { action: 'set_active'; userId: string; active: boolean }
  | { action: 'set_flags'; userId: string; isAdmin: boolean; canCreateProtocols: boolean }
  | { action: 'set_display_name'; userId: string; displayName: string }

/** All account changes go through the admin-users Edge Function. */
export function useAdminUsersAction() {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: (request: AdminUsersRequest) => invokeFunction<{ id?: string; ok?: boolean }>('admin-users', request),
    onSuccess: async () => {
      await Promise.all([
        queryClient.invalidateQueries({ queryKey: userKeys.all }),
        queryClient.invalidateQueries({ queryKey: userKeys.directory }),
        queryClient.invalidateQueries({ queryKey: ['profile'] }),
      ])
    },
  })
}

/** Protocol access is plain table writes; RLS lets only administrators make them. */
export function useAccessMutations(userId: string) {
  const queryClient = useQueryClient()
  const invalidate = () =>
    Promise.all([
      queryClient.invalidateQueries({ queryKey: userKeys.access(userId) }),
      queryClient.invalidateQueries({ queryKey: ['protocols'] }),
    ])

  const grant = useMutation({
    mutationFn: async ({ protocolId, role }: { protocolId: string; role: ProtocolRole }) => {
      const { error } = await getSupabase().from('protocol_access').insert({ protocol_id: protocolId, user_id: userId, role })
      if (error) throw error
    },
    onSuccess: invalidate,
  })

  const change = useMutation({
    mutationFn: async ({ accessId, role }: { accessId: string; role: ProtocolRole }) => {
      const { error } = await getSupabase().from('protocol_access').update({ role }).eq('id', accessId)
      if (error) throw error
    },
    onSuccess: invalidate,
  })

  const remove = useMutation({
    mutationFn: async (accessId: string) => {
      const { error } = await getSupabase().from('protocol_access').delete().eq('id', accessId)
      if (error) throw error
    },
    onSuccess: invalidate,
  })

  return { grant, change, remove }
}
